// initialize the ARIALUNI font
VGErrorCode ARIALUNIFontInit(void)
{
	Font *font = &ARIALUNI_font;
	VGErrorCode err = VG_NO_ERROR;
	const VGfloat glyphs_origin[2] = { 0.0f, 0.0f };
	
	if (font->openvgHandle == VG_INVALID_HANDLE)
	{
		// create ARIALUNI OpenVG font object
		font->openvgHandle = vgCreateFont(font->glyphsCount);
		if (font->openvgHandle != VG_INVALID_HANDLE)
		{
			VGuint i;
			// create OpenVG glyphs
			for (i = 0; i < font->glyphsCount; ++i)
			{
												// create the path object
												VGPath path = vgCreatePath (VG_PATH_FORMAT_STANDARD, 
													 VG_PATH_DATATYPE_F, 
													 1.0f, 
													 0.0f, 
													 font->glyphs[i].commandsCount, 
													 font->glyphs[i].coordinatesCount, 
													 VG_PATH_CAPABILITY_ALL
													);
				// append the glyphs's command data & coordinate data into path object
				vgAppendPathData(path, font->glyphs[i].commandsCount, font->glyphs[i].commands, font->glyphs[i].coordinates);
  				// remove "editing" capabilities, so that OpenVG driver can try to free some memory
				vgRemovePathCapabilities(path, VG_PATH_CAPABILITY_APPEND_FROM | VG_PATH_CAPABILITY_APPEND_TO |
                                           VG_PATH_CAPABILITY_MODIFY | VG_PATH_CAPABILITY_TRANSFORM_FROM |
                                           VG_PATH_CAPABILITY_TRANSFORM_TO | VG_PATH_CAPABILITY_INTERPOLATE_FROM |
                                           VG_PATH_CAPABILITY_INTERPOLATE_TO);
				// append the glyph object into the font object
   			vgSetGlyphToPath (font->openvgHandle,
										font->glyphs[i].glyphIndex, 
										path, VG_FALSE, 
										(float *)glyphs_origin, 
										(float *)font->glyphs[i].escapement);
				// destroy the path object to free the memory
				vgDestroyPath(path);
 			}
		}
		// check for errors from the OpenVG driver side
		err = vgGetError();
	}

	return err;
}
// destroy the ARIALUNI font
void ARIALUNIFontDestroy(void)
{
	Font *font = &ARIALUNI_font;
	if (font->openvgHandle != VG_INVALID_HANDLE)
	{
		 VGuint i;
		 // walk through each glyph
		 for (i = 0; i < font->glyphsCount; ++i)
		 {
			 // free the resource occupied by the glyps object & path object
			 vgClearGlyph (font->openvgHandle, font->glyphs[i].glyphIndex);
		 }
		 vgDestroyFont(font->openvgHandle);
		 font->openvgHandle = VG_INVALID_HANDLE;
	}
	
}
